"""Generates the launcher icon foreground (pixel trail cat) from app/src/main/assets/characters.txt.

Usage: python3 tools/make_icon.py
"""
import os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from sprites import parse, frame

chars = {c['id']: c for c in parse(os.path.join(ROOT, 'app/src/main/assets/characters.txt'))}
cat = chars['cat']
px = frame(cat, 1, idle=True)  # standing pose, outlined 18x18

PIXEL = 3.0                 # dp per sprite pixel
SIZE = 18 * PIXEL           # 54dp: inside the 66dp adaptive-icon safe zone
OX = (108 - SIZE) / 2
OY = (108 - SIZE) / 2 - 2   # nudge up a little so the feet sit near the centre

by_color = {}
for y in range(18):
    x = 0
    while x < 18:
        c = px[y][x]
        if c is None:
            x += 1
            continue
        run = 1
        while x + run < 18 and px[y][x + run] == c:
            run += 1
        by_color.setdefault(c, []).append(
            f"M{OX + x * PIXEL:g},{OY + y * PIXEL:g}h{run * PIXEL:g}v{PIXEL:g}h{-run * PIXEL:g}z")
        x += run

feet_y = OY + 17 * PIXEL
paths = [f'    <path android:fillColor="#38000000" android:pathData="M{54 - 17:g},{feet_y:g}a17,3.2 0,1 0,34,0a17,3.2 0,1 0,-34,0z" />']
for c, ds in by_color.items():
    paths.append(f'    <path android:fillColor="#FF{c[0]:02X}{c[1]:02X}{c[2]:02X}" android:pathData="{"".join(ds)}" />')

xml = f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/make_icon.py from assets/characters.txt. Do not edit by hand. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp"
    android:viewportWidth="108" android:viewportHeight="108">
{chr(10).join(paths)}
</vector>
'''
open(os.path.join(ROOT, 'app/src/main/res/drawable/ic_launcher_foreground.xml'), 'w').write(xml)
print('wrote foreground,', len(by_color), 'colours')
